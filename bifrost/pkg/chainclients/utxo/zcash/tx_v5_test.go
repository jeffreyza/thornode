// Consensus branch IDs either side of NU7. v5 (ZIP-225) is a valid transaction version both
// before and after NU7, so the vault signs v5 under whichever branch is active; only the branch
// commitment in the digest changes across the boundary.
const (
	branchNU61 uint32 = 0xc8e71055 // NU6.1, confirmed live by TestV5Zebra.
	branchNU7  uint32 = 0x77190ad9 // NU7.
)

type v5Vector struct {
	Name      string   `json:"name"`
	Bitcoin   string   `json:"bitcoin"`
	Raw       string   `json:"raw"`
	TxID      string   `json:"txid"`
	Branch    uint32   `json:"branch"`
	Expiry    uint32   `json:"expiry"`
	Amounts   []int64  `json:"amounts"`
	Scripts   []string `json:"scripts"`
	Sighashes []string `json:"sighashes"`
}

// buildFromBitcoin rebuilds a transparent tx from a btcd container as the given Zcash version.
func buildFromBitcoin(t *testing.T, bitcoin []byte, version int32, branch, expiry uint32) (*Tx, []*wire.TxOut) {
	t.Helper()
	tx := &Tx{MsgTx: &wire.MsgTx{}, ExpiryHeight: expiry, ConsensusBranchID: branch}
	if err := tx.MsgTx.DeserializeNoWitness(bytes.NewReader(bitcoin)); err != nil {
		t.Fatal(err)
	}
	tx.MsgTx.Version = version
	return tx, nil
}

// TestGenerateV5Vectors regenerates testdata/v5/vectors.json from the transparent shapes in the
// librustzcash-checked v6 fixtures, recomputing the v5 serialization, txid and signing digests.
// The v5 outputs are independently validated by TestV5Zebra (an official zebrad accepts them).
// Run with GEN_V5=1 to refresh the fixtures.
func TestGenerateV5Vectors(t *testing.T) {
	if os.Getenv("GEN_V5") == "" {
		t.Skip("set GEN_V5=1 to regenerate testdata/v5/vectors.json")
	}
	raw, err := os.ReadFile("testdata/v6/vectors.json")
	if err != nil {
		t.Fatal(err)
	}
	var v6 []v5Vector
	if err = json.Unmarshal(raw, &v6); err != nil {
		t.Fatal(err)
	}
	out := make([]v5Vector, 0, len(v6))
	for _, vector := range v6 {
		bitcoin, decErr := hex.DecodeString(vector.Bitcoin)
		if decErr != nil {
			t.Fatal(decErr)
		}
		tx, _ := buildFromBitcoin(t, bitcoin, 5, vector.Branch, vector.Expiry)
		previous := make([]*wire.TxOut, len(vector.Amounts))
		for i, value := range vector.Amounts {
			script, scriptErr := hex.DecodeString(vector.Scripts[i])
			if scriptErr != nil {
				t.Fatal(scriptErr)
			}
			previous[i] = wire.NewTxOut(value, script)
		}
		var buffer bytes.Buffer
		if err = tx.Serialize(&buffer); err != nil {
			t.Fatal(err)
		}
		id, idErr := tx.ID()
		if idErr != nil {
			t.Fatal(idErr)
		}
		hashes, hashErr := NewSigHashes(tx, previous)
		if hashErr != nil {
			t.Fatal(hashErr)
		}
		sighashes := make([]string, len(previous))
		for i := range previous {
			digest, sigErr := hashes.SignatureHash(i)
			if sigErr != nil {
				t.Fatal(sigErr)
			}
			sighashes[i] = hex.EncodeToString(digest)
		}
		out = append(out, v5Vector{
			Name:      vector.Name,
			Bitcoin:   vector.Bitcoin,
			Raw:       hex.EncodeToString(buffer.Bytes()),
			TxID:      id.String(),
			Branch:    vector.Branch,
			Expiry:    vector.Expiry,
			Amounts:   vector.Amounts,
			Scripts:   vector.Scripts,
			Sighashes: sighashes,
		})
	}
	encoded, err := json.MarshalIndent(out, "", "  ")
	if err != nil {
		t.Fatal(err)
	}
	if err = os.MkdirAll("testdata/v5", 0o755); err != nil {
		t.Fatal(err)
	}
	if err = os.WriteFile("testdata/v5/vectors.json", append(encoded, '\n'), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Logf("wrote %d v5 vectors", len(out))
}

// TestV5Vectors checks native bytes, transaction IDs and every input digest for transparent v5
// transactions against saved reference values. The fixtures were generated by this package and
// independently accepted by an official zebrad in TestV5Zebra.
func TestV5Vectors(t *testing.T) {
	raw, err := os.ReadFile("testdata/v5/vectors.json")
	if err != nil {
		t.Fatal(err)
	}
	var vectors []v5Vector
	if err = json.Unmarshal(raw, &vectors); err != nil {
		t.Fatal(err)
	}
	if len(vectors) == 0 {
		t.Fatal("no v5 vectors")
	}
	decode := func(s string) []byte {
		t.Helper()
		b, decErr := hex.DecodeString(s)
		if decErr != nil {
			t.Fatal(decErr)
		}
		return b
	}
	for _, vector := range vectors {
		t.Run(vector.Name, func(t *testing.T) {
			tx, _ := buildFromBitcoin(t, decode(vector.Bitcoin), 5, vector.Branch, vector.Expiry)
			if len(vector.Amounts) != len(tx.TxIn) || len(vector.Sighashes) != len(tx.TxIn) {
				t.Fatal("fixture needs one amount and sighash per input")
			}
			previous := make([]*wire.TxOut, len(vector.Amounts))
			for i, value := range vector.Amounts {
				previous[i] = wire.NewTxOut(value, decode(vector.Scripts[i]))
			}
			var buffer bytes.Buffer
			if err := tx.Serialize(&buffer); err != nil {
				t.Fatal(err)
			}
			encoded := hex.EncodeToString(buffer.Bytes())
			if encoded != vector.Raw {
				t.Fatalf("v5 serialization mismatch\n got %s\nwant %s", encoded, vector.Raw)
			}
			// Header: fOverwintered|5 then the ZIP-225 version group id.
			if binary.LittleEndian.Uint32(buffer.Bytes()[:4]) != 0x80000005 {
				t.Fatal("wrong v5 header word")
			}
			if binary.LittleEndian.Uint32(buffer.Bytes()[4:8]) != v5GroupID {
				t.Fatal("wrong v5 version group id")
			}
			restored, err := ParseTx(buffer.Bytes())
			if err != nil {
				t.Fatal(err)
			}
			if restored.Version != 5 || restored.ConsensusBranchID != vector.Branch || restored.ExpiryHeight != vector.Expiry {
				t.Fatal("v5 roundtrip changed header")
			}
			id, err := restored.ID()
			if err != nil || id.String() != vector.TxID {
				t.Fatal("v5 txid mismatch", id, err)
			}
			if id == chainhash.DoubleHashH(buffer.Bytes()) {
				t.Fatal("v5 must not use SHA256d txid")
			}
			hashes, err := NewSigHashes(tx, previous)
			if err != nil {
				t.Fatal(err)
			}
			for i, want := range vector.Sighashes {
				digest, hashErr := hashes.SignatureHash(i)
				if hashErr != nil || hex.EncodeToString(digest) != want {
					t.Fatal("v5 signing digest mismatch", i, hashErr)
				}
			}
			// An authorizing script must not change the non-malleable txid.
			tx.TxIn[0].SignatureScript = []byte{1, 2, 3}
			changed, err := tx.ID()
			if err != nil || changed != id {
				t.Fatal("authorizing script changed v5 txid", err)
			}
		})
	}
}

// sampleV5Tx builds a fixed two-input transparent payment for branch-dependence tests.
func sampleV5Tx(branch uint32) (*Tx, []*wire.TxOut) {
	tx := &Tx{MsgTx: wire.NewMsgTx(5), ConsensusBranchID: branch, ExpiryHeight: 320}
	for i := 0; i < 2; i++ {
		var hash chainhash.Hash
		hash[0] = byte(i + 1)
		tx.AddTxIn(wire.NewTxIn(wire.NewOutPoint(&hash, uint32(i)), nil, nil))
	}
	tx.AddTxOut(wire.NewTxOut(1_500_000, []byte{0x76, 0xa9, 0x14, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x88, 0xac}))
	previous := []*wire.TxOut{
		wire.NewTxOut(1_000_000, []byte{0x76, 0xa9, 0x14, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x22, 0x88, 0xac}),
		wire.NewTxOut(600_000, []byte{0x76, 0xa9, 0x14, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x33, 0x88, 0xac}),
	}
	return tx, previous
}

func serializeV5(t *testing.T, tx *Tx) []byte {
	t.Helper()
	var buffer bytes.Buffer
	if err := tx.Serialize(&buffer); err != nil {
		t.Fatal(err)
	}
	return buffer.Bytes()
}

func sighashesV5(t *testing.T, tx *Tx, previous []*wire.TxOut) [][]byte {
	t.Helper()
	hashes, err := NewSigHashes(tx, previous)
	if err != nil {
		t.Fatal(err)
	}
	out := make([][]byte, len(previous))
	for i := range previous {
		digest, hashErr := hashes.SignatureHash(i)
		if hashErr != nil {
			t.Fatal(hashErr)
		}
		out[i] = digest
	}
	return out
}

// TestV5BranchFlipDeterminism proves the only difference the branch id makes to an unsigned v5
// transaction is the 4-byte branch commitment: the serialized bytes are identical outside
// [8:12], yet the txid and every signing digest change. All signers therefore build identical
// bytes once they agree the outbound height (and thus the branch), and the digest is bound to
// that branch.
func TestV5BranchFlipDeterminism(t *testing.T) {
	txA, previous := sampleV5Tx(branchNU61)
	txB, _ := sampleV5Tx(branchNU7)

	rawA, rawB := serializeV5(t, txA), serializeV5(t, txB)
	if len(rawA) != len(rawB) {
		t.Fatal("branch flip changed length")
	}
	for i := range rawA {
		if i >= 8 && i < 12 {
			continue // The consensus branch id lives here.
		}
		if rawA[i] != rawB[i] {
			t.Fatalf("branch flip changed byte %d outside the branch field", i)
		}
	}
	if binary.LittleEndian.Uint32(rawA[8:12]) != branchNU61 || binary.LittleEndian.Uint32(rawB[8:12]) != branchNU7 {
		t.Fatal("branch not committed in header")
	}

	idA, err := txA.ID()
	if err != nil {
		t.Fatal(err)
	}
	idB, err := txB.ID()
	if err != nil {
		t.Fatal(err)
	}
	if idA == idB {
		t.Fatal("branch flip must change the txid")
	}
	digestsA, digestsB := sighashesV5(t, txA, previous), sighashesV5(t, txB, previous)
	for i := range digestsA {
		if bytes.Equal(digestsA[i], digestsB[i]) {
			t.Fatalf("branch flip must change signing digest for input %d", i)
		}
	}
	// Flipping the branch back reproduces the original digests exactly (determinism).
	txBackA, _ := sampleV5Tx(branchNU61)
	if !bytes.Equal(serializeV5(t, txBackA), rawA) {
		t.Fatal("same branch is not deterministic")
	}
	for i, again := range sighashesV5(t, txBackA, previous) {
		if !bytes.Equal(again, digestsA[i]) {
			t.Fatalf("same branch recomputed a different digest for input %d", i)
		}
	}
}

// TestV5ResignAcrossBoundary models a transparent outbound that must be re-signed when it is
// re-agreed under the NU7 branch after NU6.x. The logical payment (inputs, outputs, lock time,
// expiry) is unchanged, but the new branch yields different signing digests, a different txid and
// different wire bytes, each internally consistent and still a valid v5 transaction.
func TestV5ResignAcrossBoundary(t *testing.T) {
	txNU6, previous := sampleV5Tx(branchNU61)
	txNU7, _ := sampleV5Tx(branchNU7)

	for _, tc := range []struct {
		name string
		tx   *Tx
	}{{"nu6", txNU6}, {"nu7", txNU7}} {
		raw := serializeV5(t, tc.tx)
		restored, err := ParseTx(raw)
		if err != nil {
			t.Fatalf("%s: parse: %v", tc.name, err)
		}
		if restored.Version != 5 {
			t.Fatalf("%s: not v5 after roundtrip", tc.name)
		}
		id, err := tc.tx.ID()
		if err != nil {
			t.Fatalf("%s: id: %v", tc.name, err)
		}
		restoredID, err := restored.ID()
		if err != nil || restoredID != id {
			t.Fatalf("%s: txid not stable across roundtrip", tc.name)
		}
		// Each branch's digests recompute identically (internally consistent).
		first := sighashesV5(t, tc.tx, previous)
		for i, again := range sighashesV5(t, restored, previous) {
			if !bytes.Equal(again, first[i]) {
				t.Fatalf("%s: digest for input %d not stable", tc.name, i)
			}
		}
	}

	// Re-signing across the boundary produces different bytes and a different txid.
	if bytes.Equal(serializeV5(t, txNU6), serializeV5(t, txNU7)) {
		t.Fatal("re-sign across boundary produced identical bytes")
	}
	idNU6, err := txNU6.ID()
	if err != nil {
		t.Fatal(err)
	}
	idNU7, err := txNU7.ID()
	if err != nil {
		t.Fatal(err)
	}
	if idNU6 == idNU7 {
		t.Fatal("re-sign across boundary produced identical txid")
	}
}
